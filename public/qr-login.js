(() => {
  'use strict';
  const $ = (s) => document.querySelector(s);
  let pollTimer = 0, expiryTimer = 0, stream = null, detector = null, scanning = false;
  const modal = () => $('#qrPairModal');
  const readSession = () => { try { return JSON.parse(localStorage.getItem('fbchat-session') || 'null'); } catch { return null; } };
  const status = (text) => { $('#qrPairStatus').textContent = text; };
  function stopCamera() {
    scanning = false;
    if (stream) stream.getTracks().forEach(t => t.stop());
    stream = null;
    $('#qrPairVideo').srcObject = null;
    $('#qrPairVideo').hidden = true;
  }
  function closeModal() {
    clearInterval(pollTimer); clearTimeout(expiryTimer); pollTimer = expiryTimer = 0;
    stopCamera(); modal().hidden = true;
  }
  async function post(path, body, token) {
    const r = await fetch(path, { method: 'POST', cache: 'no-store', headers: {
      'Content-Type': 'application/json', ...(token ? { Authorization: 'Bearer ' + token } : {})
    }, body: JSON.stringify(body) });
    const data = await r.json().catch(() => ({}));
    if (!r.ok) throw new Error(data.message || 'Pairing request failed.');
    return data;
  }
  async function startPcPairing() {
    closeModal(); modal().hidden = false;
    $('#qrPairCanvas').hidden = false; $('#qrPairVideo').hidden = true; $('#qrPairStartCamera').hidden = true;
    status('Creating one-time QR code…');
    try {
      const pair = await post('/api/qr/start', {});
      const url = new URL(location.origin + '/');
      url.searchParams.set('fbpair', pair.id + '.' + pair.secret);
      if (!window.QRCode?.toCanvas) throw new Error('QR generator could not load. Refresh and retry.');
      await window.QRCode.toCanvas($('#qrPairCanvas'), url.href, { width: 280, margin: 2, errorCorrectionLevel: 'M' });
      status('Open FB Chat on your signed-in phone and choose “Scan QR with this phone”. Expires in 90 seconds.');
      const poll = async () => {
        try {
          const r = await fetch('/api/qr/status', { method: 'POST', cache: 'no-store', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ id: pair.id, secret: pair.secret }) });
          const data = await r.json().catch(() => ({}));
          if (data.status === 'approved' && data.session?.access_token && data.session?.refresh_token) {
            clearInterval(pollTimer); clearTimeout(expiryTimer);
            localStorage.setItem('fbchat-session', JSON.stringify(data.session));
            status('Approved. Enter your account password to unlock encrypted chat history on this PC…');
            const password = window.prompt('QR approved. Enter your FB Chat account password to unlock encrypted messages on this PC:');
            if (!password) { localStorage.removeItem('fbchat-session'); status('Sign-in cancelled. Generate a new QR to try again.'); return; }
            window.dispatchEvent(new CustomEvent('fbchat:qr-session-approved', { detail: { password } }));
            closeModal();
            return;
          }
          if (data.status === 'expired' || data.status === 'pending' && data.expiresIn <= 0) {
            clearInterval(pollTimer); status('QR expired. Close this window and generate a new code.');
          }
        } catch { status('Connection interrupted. Waiting to reconnect…'); }
      };
      pollTimer = setInterval(poll, 1800);
      expiryTimer = setTimeout(() => { clearInterval(pollTimer); status('QR expired. Generate a new code.'); }, 90_000);
    } catch (e) { status(e.message || 'Could not create QR code.'); }
  }
  async function approveScannedCode(raw) {
    const session = readSession();
    if (!session?.access_token || !session?.refresh_token || !session?.user) {
      throw new Error('First sign in to FB Chat on this phone, then scan again.');
    }
    let parsed;
    try { parsed = new URL(raw); } catch { throw new Error('That is not a valid FB Chat pairing QR.'); }
    if (parsed.origin !== location.origin) throw new Error('For your safety, scan a QR generated by this FB Chat site only.');
    const value = parsed.searchParams.get('fbpair') || '';
    const match = value.match(/^([a-f0-9]{32})\.([A-Za-z0-9_-]{40,60})$/);
    if (!match) throw new Error('QR code is invalid or expired.');
    await post('/api/qr/approve', { id: match[1], secret: match[2], session }, session.access_token);
    status('Phone approved this PC. Completing sign-in…');
    stopCamera();
  }
  async function startCamera() {
    const session = readSession();
    if (!session?.access_token) { status('Sign in on this phone first, then scan the PC QR.'); return; }
    if (!('BarcodeDetector' in window)) {
      status('QR scanning is not supported in this browser. Open the PC QR URL on this phone instead, while signed in.');
      return;
    }
    try {
      detector = new BarcodeDetector({ formats: ['qr_code'] });
      stream = await navigator.mediaDevices.getUserMedia({ video: { facingMode: 'environment' }, audio: false });
      const video = $('#qrPairVideo'); video.srcObject = stream; video.hidden = false;
      $('#qrPairCanvas').hidden = true; await video.play(); scanning = true;
      status('Point your camera at the QR code on the PC.');
      const scan = async () => {
        if (!scanning || !stream) return;
        try {
          const codes = await detector.detect(video);
          if (codes?.[0]?.rawValue) {
            scanning = false;
            await approveScannedCode(codes[0].rawValue);
            status('Approved! The PC will sign in shortly.');
            setTimeout(closeModal, 1600);
            return;
          }
        } catch {}
        if (scanning) requestAnimationFrame(scan);
      };
      requestAnimationFrame(scan);
    } catch (e) { status(e.message || 'Camera permission is needed to scan QR codes.'); }
  }
  document.addEventListener('DOMContentLoaded', () => {
    $('#showQrLogin')?.addEventListener('click', startPcPairing);
    $('#scanQrDeviceButton')?.addEventListener('click', () => {
      closeModal(); modal().hidden = false;
      $('#qrPairCanvas').hidden = true; $('#qrPairVideo').hidden = true;
      $('#qrPairStartCamera').hidden = false;
      status('Scan the one-time QR code shown on your PC.');
    });
    $('#scanQrLogin')?.addEventListener('click', () => {
      closeModal(); modal().hidden = false;
      $('#qrPairCanvas').hidden = true; $('#qrPairVideo').hidden = true;
      $('#qrPairStartCamera').hidden = false;
      status('Use the signed-in phone to scan a QR shown on your PC.');
    });
    $('#qrPairStartCamera')?.addEventListener('click', () => { void startCamera().catch(e => status(e.message)); });
    $('#qrPairClose')?.addEventListener('click', closeModal);
    $('#qrPairCancel')?.addEventListener('click', closeModal);
    modal()?.addEventListener('click', e => { if (e.target === modal()) closeModal(); });
    const session = readSession();
    if ($('#scanQrLogin')) $('#scanQrLogin').hidden = !session?.access_token;
    // If this phone opens a QR pairing link directly, approve it only after explicit confirmation.
    const pairValue = new URL(location.href).searchParams.get('fbpair');
    if (pairValue && session?.access_token) {
      modal().hidden = false; $('#qrPairCanvas').hidden = true; $('#qrPairStartCamera').hidden = true;
      status('This PC is requesting to link to your account. Confirm only if you started this request.');
      const confirm = document.createElement('button');
      confirm.type = 'button'; confirm.className = 'primary'; confirm.textContent = 'Approve PC sign-in';
      confirm.addEventListener('click', async () => {
        confirm.disabled = true;
        try { await approveScannedCode(location.href); status('Approved.'); history.replaceState({}, '', location.pathname); setTimeout(closeModal, 1200); }
        catch (e) { status(e.message); confirm.disabled = false; }
      });
      $('#qrPairStatus').after(confirm);
    }
  });
  window.addEventListener('beforeunload', stopCamera);
})();